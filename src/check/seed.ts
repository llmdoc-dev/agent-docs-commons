const BY_SLUG = new Map(SERVICES.map((s) => [s.slug, s]));

export function listServices(): ServiceRecord[] {
  return SERVICES;
}

export function getService(slug: string): ServiceRecord | undefined {
  return BY_SLUG.get(slug.trim().toLowerCase());
}

export function serviceCount(): number {
  return SERVICES.length;
}

export function servicesWithVerifiedPrices(): number {
  return SERVICES.filter((s) => s.freshness === "verified" || s.freshness === "partial").length;
}


export function getServiceByDocsLibrary(library: string): ServiceRecord | undefined {
  const slug = library.trim().toLowerCase();
  return SERVICES.find((s) => s.docsLibrary === slug || s.slug === slug);
}
